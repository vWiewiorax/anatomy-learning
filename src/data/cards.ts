function with3d(c: Card): Card {
  const o = IMAGE_3D[c.id];
  if (!o) return { ...c, credit: c.image ? BP3D_CREDIT : undefined };
  return { ...c, image: o.image, credit: o.credit === "BP3D" ? BP3D_CREDIT : (o.credit ?? undefined) };
}

